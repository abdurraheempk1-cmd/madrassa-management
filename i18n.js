  function lang() {
    const raw = String(localStorage.getItem(KEY) || localStorage.getItem('madrassaLanguage') || 'ur').toLowerCase();
    return SUPPORTED.includes(raw) ? raw : 'ur';
  }

  function setLang(l) {
    l = SUPPORTED.includes(l) ? l : 'ur';
    [KEY,'madrassaLanguage','selectedLanguage','siteLanguage','language'].forEach(k => {
      try { localStorage.setItem(k,l); } catch (_) {}
    });
    apply(l);
  }

  function t(value, l = lang()) {
    if (value === null || value === undefined) return '';
    const original = String(value);
    if (l === 'ur') return original;
    const trimmed = original.trim();
    if (!trimmed) return original;
    const exact = D[trimmed];
    if (exact) {
      const translated = exact[index[l]] || trimmed;
      return original.replace(trimmed, translated);
    }
    let out = original;
    // Translate known phrases inside mixed UI strings without touching user-entered values.
    Object.keys(D).sort((a,b)=>b.length-a.length).forEach(k => {
      if (k.length < 3 || !out.includes(k)) return;
      const v = D[k][index[l]];
      if (v) out = out.split(k).join(v);
    });
    if (out !== original) return out;
    // Lightweight fallback for short labels only.
    if (trimmed.length <= 70) {
      replacements.forEach(([k,v]) => { if (out.includes(k)) out = out.split(k).join(v[index[l]]); });
    }
    return out;
  }

  function translateTextNode(node, l) {
    if (!node || node.nodeType !== Node.TEXT_NODE) return;
    const p = node.parentElement;
    if (!p || p.closest('script,style,textarea,[contenteditable="true"],.notranslate,[data-no-translate]')) return;
    const current = node.nodeValue || '';
    const last = lastRenderedText.get(node);
    if (!sourceText.has(node) || (last !== undefined && current !== last)) {
      sourceText.set(node,current);
    }
    const source = sourceText.get(node) || current;
    const nv = l === 'ur' ? source : t(source,l);
    lastRenderedText.set(node,nv);
    if (node.nodeValue !== nv) node.nodeValue = nv;
  }

  function translateElement(el, l) {
    if (!el || el.nodeType !== Node.ELEMENT_NODE) return;
    if (el.matches('.notranslate,[data-no-translate]') || el.closest('.notranslate,[data-no-translate]')) return;
    let attrs = sourceAttrs.get(el);
    if (!attrs) { attrs = {}; sourceAttrs.set(el,attrs); }
    ['placeholder','title','aria-label'].forEach(attr => {
      if (el.hasAttribute(attr)) {
        const current = el.getAttribute(attr) || '';
        if (!(attr in attrs)) attrs[attr] = current;
        const source = attrs[attr];
        const nv = l === 'ur' ? source : t(source,l);
        if (current !== nv) el.setAttribute(attr,nv);
      }
    });
    Array.from(el.childNodes).forEach(n => {
      if (n.nodeType === Node.TEXT_NODE) translateTextNode(n,l);
    });
  }

  function walk(root, l) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) return translateTextNode(root,l);
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) translateElement(root,l);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let n;
    while ((n = w.nextNode())) {
      if (n.nodeType === Node.TEXT_NODE) translateTextNode(n,l); else translateElement(n,l);
    }
  }

  function ensureSelector(l) {
    const existing = document.getElementById('globalLanguageSelector') || document.getElementById('languageSelector') || document.getElementById('loginLanguage');
    if (existing) {
      existing.value = l;
      if (!existing.dataset.globalLanguageBound) {
        existing.dataset.globalLanguageBound = '1';
        existing.addEventListener('change', e => setLang(e.target.value));
      }
      return;
    }
    const wrap = document.createElement('div');
    wrap.className = 'global-language-switcher no-print notranslate';
    wrap.innerHTML = '<label for="globalLanguageSelector">🌐</label><select id="globalLanguageSelector" aria-label="Language"><option value="ur">اردو</option><option value="en">English</option><option value="ar">العربية</option><option value="ps">پښتو</option></select>';
    document.body.appendChild(wrap);
    const sel = wrap.querySelector('select');
    sel.value = l;
    sel.addEventListener('change', e => setLang(e.target.value));
  }

  function apply(l = lang()) {
    l = SUPPORTED.includes(l) ? l : 'ur';
    document.documentElement.lang = l;
    document.documentElement.dir = RTL.has(l) ? 'rtl' : 'ltr';
    document.body && document.body.setAttribute('data-language',l);
    ensureSelector(l);
    walk(document.body,l);
    if (document.title) {
      if (!sourceTitle || (l === 'ur' && /[\u0600-\u06ff]/.test(document.title))) sourceTitle = document.title;
      document.title = l === 'ur' ? sourceTitle : t(sourceTitle,l);
    }
    document.dispatchEvent(new CustomEvent('madrassa:languagechange',{detail:{language:l}}));
  }

  const nativeAlert = window.alert.bind(window);
  const nativeConfirm = window.confirm.bind(window);
  const nativePrompt = window.prompt.bind(window);
  window.alert = msg => nativeAlert(t(msg));
  window.confirm = msg => nativeConfirm(t(msg));
  window.prompt = (msg, def) => nativePrompt(t(msg), def);

  let observer;
  function boot() {
    const file = (location.pathname.split("/").pop() || "index.html").toLowerCase();
    if (file === "index.html" || file === "login.html" || file === "") {
      // These two pages already contain their own complete language engines.
      // Do not translate them twice; only keep the shared language key synchronized.
      const selector = document.getElementById(file === "login.html" ? "loginLanguage" : "languageSelector");
      if (selector && selector.dataset.sharedLanguageBound !== "1") {
        selector.dataset.sharedLanguageBound = "1";
        selector.addEventListener("change", e => {
          const l = SUPPORTED.includes(e.target.value) ? e.target.value : "ur";
          try { localStorage.setItem(KEY,l); } catch (_) {}
        });
      }
      return;
    }
    sourceTitle = document.title || '';
    apply(lang());
    observer = new MutationObserver(mutations => {
      const l = lang();
      for (const m of mutations) {
        if (m.type === 'characterData') translateTextNode(m.target,l);
        m.addedNodes.forEach(n => walk(n,l));
      }
    });
    observer.observe(document.documentElement,{subtree:true,childList:true,characterData:true});
  }

  window.MadrassaI18n = { get: lang, set: setLang, apply, t, translations: D };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded',boot,{once:true}); else boot();
